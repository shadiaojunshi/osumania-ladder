const fs = require('fs')
const path = require('path')

const tournamentsDir = path.join(__dirname, '..', 'data', 'tournaments')
const outputFile = path.join(__dirname, '..', 'src', 'generated', 'tournaments.ts')

const files = fs.readdirSync(tournamentsDir).filter(f => f.endsWith('.json'))

const imports = files.map((f, i) => {
  return `import t${i} from '@data/tournaments/${f}'`
}).join('\n')

const output = `// Auto-generated - do not edit manually
// Run: node scripts/generate-tournaments.js
import type { Tournament } from '@/lib/types'

${imports}

export const tournaments = [
${files.map((_, i) => `  t${i},`).join('\n')}
] as unknown as Tournament[]
`

const outputDir = path.dirname(outputFile)
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true })
}

fs.writeFileSync(outputFile, output)
console.log(`Generated tournaments index with ${files.length} tournaments`)

// 构建时发现图标，浏览器无需给每场比赛逐个发 404 探测请求。
const iconsDir = path.join(__dirname, '..', 'public', 'tournament-icons')
const iconFiles = fs.existsSync(iconsDir) ? fs.readdirSync(iconsDir) : []
const ids = new Set(files.map(f => JSON.parse(fs.readFileSync(path.join(tournamentsDir, f), 'utf8')).id))
const icons = Object.create(null)
for (const file of iconFiles.sort()) {
  const ext = path.extname(file).toLowerCase()
  const id = path.basename(file, path.extname(file))
  if (!['.png', '.webp', '.jpg', '.jpeg', '.svg', '.avif'].includes(ext) || !ids.has(id)) continue
  if (icons[id]) throw new Error(`Duplicate tournament icon for ${id}: keep one image per ID`)
  icons[id] = `/tournament-icons/${encodeURIComponent(file)}`
}
fs.writeFileSync(path.join(outputDir, 'tournamentIcons.ts'),
  `// Auto-generated by scripts/generate-tournaments.js\nexport const tournamentIcons: Record<string, string> = ${JSON.stringify(icons, null, 2)}\n`)
console.log(`Generated icon index with ${Object.keys(icons).length} icons`)
